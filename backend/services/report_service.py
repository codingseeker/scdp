"""
services/report_service.py — Render simulation results into a human-readable report.

Produces a Markdown report from a stored SimulationResult (as dict) so users
can download an audit-friendly snapshot of a simulation run.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Dict

SEVERITY_LABELS = {"CRITICAL": "Critical", "HIGH": "High", "MEDIUM": "Medium", "LOW": "Low"}


def _severity_label(value) -> str:
    return SEVERITY_LABELS.get(str(value).upper(), str(value))


def render_simulation_report(result: Dict) -> str:
    scenario_id = result.get("scenario_id", "unknown")
    lines: list[str] = [
        "# Supply Chain Disruption Predictor — Simulation Report",
        "",
        f"- **Scenario**: {result.get('scenario_description', '') or 'N/A'}",
        f"- **Scenario ID**: {scenario_id}",
        f"- **Generated**: {datetime.now(timezone.utc).isoformat()}",
        f"- **Network impact**: {result.get('overall_network_impact', 0)}/100",
        f"- **Time to impact**: {result.get('time_to_impact_days', 'N/A')} day(s)",
        f"- **Affected suppliers**: {len(result.get('affected_suppliers', [])) or 0}",
        "",
        "## Executive Summary",
        "",
        result.get("executive_summary", "") or "No summary generated.",
        "",
        "## Affected Suppliers",
        "",
    ]

    affected = result.get("affected_suppliers", []) or []
    if affected:
        lines.append("| Supplier | Impact | Time to Impact | Depth | Primary Risk Factor |")
        lines.append("|----------|--------|----------------|-------|---------------------|")
        for supplier in affected:
            lines.append(
                "| {name} ({sid}) | {impact}/100 | {time}d | {depth} | {factor} |".format(
                    name=supplier.get("supplier_name", "?"),
                    sid=supplier.get("supplier_id", ""),
                    impact=supplier.get("impact_score", 0),
                    time=supplier.get("time_to_impact_days", 0),
                    depth=supplier.get("cascade_depth", 0),
                    factor=supplier.get("primary_risk_factor", "N/A"),
                )
            )
    else:
        lines.append("No suppliers impacted.")
    lines.append("")

    cascade = result.get("cascade_path", []) or []
    lines.append("## Cascade Path")
    lines.append("")
    lines.append(" → ".join(map(str, cascade)) if cascade else "No cascade detected.")
    lines.append("")

    routes = result.get("alternative_routes", []) or []
    lines.append("## Alternative Routes")
    lines.append("")
    if routes:
        for route in routes:
            lines.append(
                f"- **{route.get('route_id', '')}** — {route.get('description', '')} "
                f"(reliability {route.get('reliability_score', 'N/A')}, "
                f"cost premium {route.get('cost_premium_pct', 0)}%, "
                f"lead time {route.get('lead_time_delta_days', 0)}d)"
            )
    else:
        lines.append("No alternative routes identified.")
    lines.append("")

    actions = result.get("mitigation_actions", []) or []
    lines.append("## Recommended Actions")
    lines.append("")
    if actions:
        for action in actions:
            lines.append(f"- {action}")
    else:
        lines.append("No mitigation actions generated.")
    lines.append("")

    if result.get("ai_enriched"):
        lines.extend(
            [
                "---",
                "",
                f"*AI enrichment: enabled (model {result.get('ai_model_version', 'unknown')}, "
                f"confidence {result.get('confidence_score', 'N/A')}).*",
                "",
            ]
        )
    else:
        lines.append("---")
        lines.append("")
        lines.append("*Report generated by the deterministic simulation engine (no external AI used).*")
        lines.append("")

    return "\n".join(lines)